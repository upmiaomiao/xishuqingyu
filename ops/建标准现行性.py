CORE_RX = re.compile(r"(GB\s*/?\s*T?|HJ\s*/?\s*T?|DB\s*\d{2}\s*/?\s*T?)\s*([\d.]+)")
LAW_KEYS = ("中华人民共和国", "法典")


def core_of(row: dict) -> str:
    """从标题/标准号里抠出数字核心，用于匹配 VERIFY。"""
    sid = (row.get("standard_id") or "").strip()
    title = row.get("title") or ""
    for s in (sid, title):
        m = CORE_RX.search(s)
        if m:
            return m.group(2).rstrip(".")
    return ""


def main() -> int:
    rows = json.load(io.open(SRC, encoding="utf-8"))
    entries, unmatched, by_hard, inconsistent = [], [], {}, []
    for r in rows:
        title = r["title"] or r["source"].split("/")[-1]
        is_law = any(k in title for k in LAW_KEYS)
        core = "法典" if is_law else core_of(r)
        v = VERIFY.get(core)
        if v is None:
            unmatched.append({"标题": title, "标准号": r.get("standard_id"), "核心": core})
            v = {"替代": "（待核）", "日期": "（待核）",
                 "依据": "库内有状态/依据，但外部核实表里没有这一条", "硬度": "软-待核", "来源": []}
        st = r.get("status") or {}
        entries.append({
            "标题": title,
            "标准号": r.get("standard_id") or "",
            "材料类型": r.get("doc_type") or "",
            "库内状态": "已废止" if "已废止" in "".join(st.keys()) else "、".join(st.keys()),
            "库内块数": r["块数"],
            "库内依据原文": r.get("status_note") or "",
            "替代": v["替代"],
            "时效变化": v["日期"],
            "外部依据": v["依据"],
            "依据硬度": v["硬度"],
            "库内与官方不一致": v.get("不一致", ""),
            "来源": v["来源"],
            "核实日期": TODAY,
            "语料来源": r["source"],
        })
        by_hard[v["硬度"]] = by_hard.get(v["硬度"], 0) + 1
        if v.get("不一致"):
            inconsistent.append({"标题": title, "不一致": v["不一致"]})

    doc = {
        "用途": "A2 引用标准现行性核对（审核侧读它判断‘这个标准还有效吗’）",
        "生成方式": "导出状态清单.py 读线上索引 → 与本文件内的外部核实表合成；库里有而核实表没有的会标‘待核’",
        "生成时间": TODAY,
        "索引快照": "由 /tmp/状态清单.json 决定（见各条‘库内块数’）",
        "硬度说明": {
            "硬-官方": "生态环境部/全国人大 的公告、解读、标准发布页（带 URL）",
            "硬-标准自身": "新标准正文写明‘代替 XXX’（带 URL）",
            "软-待核": "只来自语料目录标注，**未联网核实** —— A2 上线前必须补官方依据",
        },
        "统计": {"条目数": len(entries), "按硬度": by_hard,
                 "外部未覆盖条数": len(unmatched),
                 "库内标记与官方口径不一致": len(inconsistent)},
        "库内不一致清单": inconsistent,
        "条目": entries,
    }
    io.open(OUT_JSON, "w", encoding="utf-8").write(
        json.dumps(doc, ensure_ascii=False, indent=1))

    lines = ["# 标准现行性底稿（A2）", "",
             "> 由 `建标准现行性.py` 生成，共 **%d** 条；硬度分布 %s。" % (
                 len(entries), "、".join("%s %d" % (k, v) for k, v in sorted(by_hard.items()))),
             "> 软的条目 **A2 上线前必须补官方依据**（现在只是目录标注）。", "",
             "| # | 材料 | 库内状态 | 替代 | 时效变化 | 硬度 |", "| --- | --- | --- | --- | --- | --- |"]
    for i, e in enumerate(entries, 1):
        lines.append("| %d | %s | %s | %s | %s | %s |" % (
            i, e["标题"][:44], e["库内状态"], e["替代"][:44], e["时效变化"], e["依据硬度"]))
    if unmatched:
        lines += ["", "## 库里还没有外部依据的条目（待补）", ""]
        lines += ["- %s（%s）" % (u["标题"][:60], u["标准号"] or u["核心"] or "无标准号")
                  for u in unmatched]
    if inconsistent:
        lines += ["", "## ⚠ 库内标记与官方口径不一致（A2 上线前必须处理）", ""]
        lines += ["- **%s**：%s" % (u["标题"][:50], u["不一致"]) for u in inconsistent]
    io.open(OUT_MD, "w", encoding="utf-8").write("\n".join(lines) + "\n")

    print("库内材料 %d 份 → 条目 %d 条（去重前）" % (len(rows), len(entries)))
    print("硬度分布：" + "、".join("%s=%d" % (k, v) for k, v in sorted(by_hard.items())))
    if inconsistent:
        print("\n⚠ 库内标记与官方口径不一致 %d 条：" % len(inconsistent))
        for u in inconsistent:
            print("   · %s\n     %s" % (u["标题"][:52], u["不一致"][:150]))
    if unmatched:
        print("\n⚠ 外部核实表没覆盖的 %d 条（已标待核，必须补）：" % len(unmatched))
        for u in unmatched:
            print("   · %s ｜ 标准号=%s ｜ 数字核心=%s" % (u["标题"][:52], u["标准号"], u["核心"]))
    print("\n→ %s\n→ %s" % (OUT_JSON, OUT_MD))
    return 0


if __name__ == "__main__":
    sys.exit(main())
