#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""修复操作日志的编码：原文件是 GBK，被按 UTF-8 追加后混编了。

做法：按原编码读回 → 去掉误追加的 P6 块 → 整文件转成 UTF-8 写回 →
再以 UTF-8 追加 P6 条目（不再二次追加，本次一次到位）。
"""
import io
import os
import sys

LOG = r"D:\项目\中节能\0911训练\_工作记录\操作日志\2026-09-16.md"
raw = open(LOG, "rb").read()

text = None
used = None
for enc in ("utf-8", "gbk", "gb18030"):
    try:
        text = raw.decode(enc)
        used = enc
        break
    except UnicodeDecodeError:
        continue
if text is None:
    sys.exit("无法解码，需人工处理")

print(f"原文件按 {used} 解码成功，长度 {len(text)} 字符")

MARK = "## P6 语料表格丢失诊断与正文回填"
if MARK in text:
    text = text[: text.index(MARK)].rstrip() + "\n"
    print("已去掉误追加的 P6 块")

ENTRY = """
## P6 语料表格丢失诊断与正文回填（09:00-09:40）

- 诊断：2110/3452 份文档（61%）的表格位置是死链图片引用（19060 处，图片 0 张存世），
  md 相对同源 PDF 缺 210 万字（9%）。线上表现为「材料未提供表1数值」类拒答。
- 诊断中排除的两个假设：重排服务本身正常（0.869/0.798/0.000016 分层明显）；
  内容其实已在库里（GB 18599 的 1.0×10-5 与 0.75、储油库的 ≤25/≥95 都在 block 内），
  捞不出来是因为块里没有标准名 + 表格混在散文块里。
- 修复工具：_脚本代码/数据清洗/语料正文回填.py（锚点内联回填 + 段落级差集 + 结构化表格还原）。
- 执行：缺口 >=1500 字的 315 份 + 5 份关键业务文档（危废名录/储油库/制糖/GB 18599/海水水质）。
- 补录重复率 5.0%（追加 786 万字，其中约 39 万字原文已有）。
- 索引：线上 45207 chunks / 262M → 暂存 70855 chunks / 471M（+57%）。
- 检索层：chunk 加来源抬头（标准名+标准号）、表格单独成块、召回 20→60、
  引用按标准化标准号去重（同一来源上限 2 条）、索引目录支持 RAG_INDEX_DIR 覆盖。
- 验证：回归基线全部通过；6 题专业问答「数值全部命中」0 → 3；
  危废代码题从「需查阅《医疗废物分类目录》」变为 5 个代码全部答出；
  储油库答出 NMHC ≤25 g/m³、处理效率 ≥95%；制糖答出 100/120/40/50 档限值。
- 未切换线上 8011。retriever.py 已落盘（备份 retriever.py.bak_20260916），重启才生效。
- 待办：① md 里 LaTeX 数字需归一化（`$1.0{\\times}10^{-5}$` 让模型读不出数值）；
  ② 海水水质 GB 3097 等正文确实未采集，需外部获取；③ 其余 1795 份含死链文档未回填。
- 详见 变更说明/2026-09-16-语料表格丢失与正文回填-P6.md

> 编码说明：本文件原为 GBK，本次追加时曾按 UTF-8 写入导致混编，
> 已按 GBK 读回并**整体转为 UTF-8**，便于后续工具统一读取。
"""
with io.open(LOG, "w", encoding="utf-8", newline="\n") as f:
    f.write(text.rstrip() + "\n" + ENTRY)
print(f"已写回 UTF-8，长度 {os.path.getsize(LOG)} 字节")
